import { chromium, devices } from '@playwright/test';
const b = await chromium.launch({ channel: 'chrome' });
const out = process.argv[2];
const ctx = await b.newContext({ ...devices['iPhone 13'], colorScheme: 'dark', locale: 'pt-BR', timezoneId: 'America/Sao_Paulo' });
const p = await ctx.newPage();
const li = (ms) => { const d = new Date(Date.now() - ms); const z = (n) => String(n).padStart(2, '0'); return `${d.getFullYear()}-${z(d.getMonth()+1)}-${z(d.getDate())}T${z(d.getHours())}:${z(d.getMinutes())}`; };
await p.goto('http://127.0.0.1:4173/');
await p.getByTestId('onb-next').click();
await p.screenshot({ path: `${out}/1-onb-produtos.png` });
await p.getByRole('button', { name: 'Vape / pod' }).click(); await p.getByTestId('onb-next').click();
await p.getByPlaceholder('ex.: 10').fill('10'); await p.getByPlaceholder('ex.: 12,50').fill('12'); await p.getByTestId('onb-next').click();
for (let i = 0; i < 3; i++) await p.getByTestId('onb-next').click();
await p.locator('input[type=datetime-local]').fill(li(12 * 86400000)); await p.getByTestId('onb-next').click();
for (let i = 0; i < 3; i++) await p.getByTestId('onb-next').click();
await p.getByRole('heading', { name: 'Agora' }).waitFor();
await p.screenshot({ path: `${out}/2-painel.png`, fullPage: true });
await p.getByTestId('sos').click(); await p.getByTestId('sos-timer').waitFor(); await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/3-sos.png` });
await p.getByTestId('sos-passed').click();
await p.screenshot({ path: `${out}/4-sos-saida.png` });
await p.getByRole('radio', { name: '3' }).click(); await p.getByTestId('sos-save-resisted').click();
await p.getByRole('button', { name: 'Registrar lapso' }).click();
await p.screenshot({ path: `${out}/5-lapso.png`, fullPage: true });
await p.getByTestId('slip-save').click(); await p.getByText('Um lapso não apaga o caminho.').waitFor();
await p.screenshot({ path: `${out}/6-pos-lapso.png`, fullPage: true });
await p.getByRole('button', { name: 'Voltar ao painel' }).click();
await p.getByRole('link', { name: 'Histórico' }).click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/7-historico.png`, fullPage: true });
await p.getByRole('link', { name: 'Ajustes' }).click(); await p.getByRole('button', { name: 'Backups e restauração' }).click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/8-backup.png`, fullPage: true });
const light = await b.newContext({ ...devices['iPhone 13'], colorScheme: 'light', locale: 'pt-BR' });
const q = await light.newPage(); await q.goto('http://127.0.0.1:4173/'); await q.getByTestId('onb-next').click();
await q.screenshot({ path: `${out}/9-claro.png` });
await b.close(); console.log('ok');
