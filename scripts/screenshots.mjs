// Capturas das telas principais (iPhone 13, escuro). Uso: npm run preview & node scripts/screenshots.mjs <pasta>
import { chromium, devices } from '@playwright/test';
const b = await chromium.launch({ channel: 'chrome' });
const out = process.argv[2] ?? 'shots';
const ctx = await b.newContext({ ...devices['iPhone 13'], colorScheme: 'dark', locale: 'pt-BR', timezoneId: 'America/Sao_Paulo' });
const p = await ctx.newPage();
const li = (ms) => { const d = new Date(Date.now() - ms); const z = (n) => String(n).padStart(2, '0'); return `${d.getFullYear()}-${z(d.getMonth()+1)}-${z(d.getDate())}T${z(d.getHours())}:${z(d.getMinutes())}`; };
await p.goto('http://127.0.0.1:4173/');
await p.getByTestId('onb-next').click();
await p.getByRole('button', { name: 'Vape / pod' }).click(); await p.getByTestId('onb-next').click();
await p.getByRole('button', { name: 'Vape / pod' }).click();
await p.getByRole('button', { name: '3 dias' }).click(); await p.getByTestId('cons-price').fill('60');
await p.screenshot({ path: `${out}/1-consumo.png`, fullPage: true });
await p.getByTestId('onb-next').click();
for (let i = 0; i < 3; i++) await p.getByTestId('onb-next').click();
await p.locator('input[type=datetime-local]').fill(li(12 * 86400000)); await p.getByTestId('onb-next').click();
for (let i = 0; i < 3; i++) await p.getByTestId('onb-next').click();
await p.getByTestId('sos').waitFor(); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/2-agora.png`, fullPage: true });
await p.getByTestId('sos').click(); await p.getByTestId('sos-timer').waitFor(); await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/3-sos.png` });
await p.getByTestId('sos-passed').click(); await p.getByRole('radio', { name: '3' }).click(); await p.getByTestId('sos-save-resisted').click();
await p.getByRole('button', { name: 'Humor bem' }).click(); await p.getByRole('radiogroup', { name: 'Sono (noite passada)' }).getByRole('radio', { name: '4' }).click(); await p.getByTestId('diary-save').click();
await p.getByRole('link', { name: 'Tendências' }).click(); await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/4-tendencias.png`, fullPage: true });
await p.getByRole('link', { name: 'Histórico' }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/5-historico.png`, fullPage: true });
await p.getByRole('link', { name: /Linha do tempo/ }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/6-linha-do-tempo.png`, fullPage: true });
await b.close(); console.log('ok');
